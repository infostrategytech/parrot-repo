using System.Security.Claims;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Parrot.Api.Monitoring;
using Parrot.Api.Security;
using Parrot.Application.Auth;
using Parrot.Application.Conversations;
using Parrot.Domain.Exceptions;

namespace Parrot.Api.Controllers;

/// <summary>
/// What the AI orchestrator calls to send a reply on behalf of a workspace.
/// Only a service token with the agent:service scope opens it; a session
/// token is refused. The tenant (workspace) is read from the token alone.
/// </summary>
[ApiController]
[Route("api/internal/conversations")]
[Authorize(Policy = ServiceScopes.PolicyName)]
[ResponseCache(NoStore = true, Location = ResponseCacheLocation.None)]
[Monitor(Area = "internal.conversations")]
public sealed class InternalConversationsController(ConversationService service) : ControllerBase
{
    private string Tenant() =>
        User.FindFirstValue(ServiceScopes.TenantClaim)
        ?? User.FindFirstValue(ClaimTypes.NameIdentifier)
        ?? User.FindFirstValue("sub")
        ?? throw new UnauthorizedException("The service token names no tenant.");

    /// <summary>
    /// Sends a reply generated by the AI agent to the customer on the given
    /// connection. After a successful send, Parrot publishes a MessagePersisted
    /// event with comms_type=AgentToUser so the orchestrator can track it.
    /// The same requestId is safe to retry; it delivers once.
    /// </summary>
    [Monitor("internal.conversations.agent_reply", SlowMs = 3000)]
    [HttpPost("{connectionId:guid}/agent-reply")]
    public async Task<IActionResult> AgentReply(Guid connectionId, [FromQuery] string sender,
        [FromBody] SendReplyRequest request, CancellationToken cancellationToken) =>
        Ok(await service.SendAgentReplyAsync(Tenant(), connectionId, sender, request, cancellationToken));
}
