// Generates the C# TextStyle enum from typography.css.
//
//   node design-system/tools/build-text-styles.mjs [--out <path>]
//
// The React build did this the other way round: lint-design-system.mjs parsed
// TEXT_STYLES out of Typography.tsx with a regex, asserted there were exactly
// 41 of them, and checked each had a matching class. That put the source of
// truth in a TypeScript file, policed by a magic number that breaks the day a
// 42nd style is drawn.
//
// Here the stylesheet is the source of truth — which it morally already was,
// since its own header documents the styles — and the C# is derived from it.
// The contract stops being an assertion and becomes a regeneration diff: if
// this file is stale, CI's `git diff --exit-code` says so.
import fs from "node:fs";
import path from "node:path";
import { REPO, TYPOGRAPHY_CSS, TEXT_STYLE_CS, TEXT_STYLE_NAMESPACE, rel } from "./paths.mjs";

const CSS = TYPOGRAPHY_CSS;

const outFlag = process.argv.indexOf("--out");
const OUT = outFlag !== -1 && process.argv[outFlag + 1] ? path.resolve(REPO, process.argv[outFlag + 1]) : TEXT_STYLE_CS;

// .ds-prose and .ds-overline are modifiers you combine WITH a text style, not
// styles in their own right, so they are not enum members.
const MODIFIERS = new Set(["prose", "overline"]);

const css = fs.readFileSync(CSS, "utf8").replace(/\/\*[\s\S]*?\*\//g, "");

if (/@media|@supports/.test(css)) {
  // The parser below strips declaration blocks with a flat brace match, which
  // a nested at-rule would break. Nothing nests today; fail loudly if it does.
  console.error("build-text-styles: typography.css now nests at-rules — the selector parser needs updating");
  process.exit(1);
}

// Drop every declaration block, leaving only selector text. Most rules here
// group their selectors on a single line, so anchoring on the start of a line
// would only ever see the first selector of each group.
const selectorText = css.replace(/\{[^{}]*\}/g, "\n");

const names = [
  ...new Set([...selectorText.matchAll(/\.ds-([a-z0-9-]+)/g)].map((m) => m[1]))
].filter((n) => !MODIFIERS.has(n));

if (names.length === 0) {
  console.error(`build-text-styles: no .ds-* selectors found in ${CSS}`);
  process.exit(1);
}

// body-small-semibold -> BodySmallSemibold;  small-10-regular -> Small10Regular
const pascal = (name) =>
  name.split("-").map((part) => part[0].toUpperCase() + part.slice(1)).join("");

const members = names.map((n) => ({ name: n, member: pascal(n) }));

const duplicates = members
  .map((m) => m.member)
  .filter((m, i, all) => all.indexOf(m) !== i);
if (duplicates.length) {
  console.error(`build-text-styles: two classes collapse to one C# name: ${duplicates.join(", ")}`);
  process.exit(1);
}

const enumBody = members
  .map(({ name, member }) => `    /// <summary>.ds-${name}</summary>\n    ${member},`)
  .join("\n");

const lookup = members.map(({ name }) => `        "ds-${name}",`).join("\n");

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(
  OUT,
  `// <auto-generated>
//     Generated by design-system/tools/build-text-styles.mjs from
//     wwwroot/css/typography.css. Do not edit by hand.
//
//     To add a text style: draw it in Figma, add the class to typography.css,
//     then re-run the generator. The stylesheet is the source of truth.
// </auto-generated>
#nullable enable

namespace ${TEXT_STYLE_NAMESPACE};

/// <summary>
/// The text styles defined in Figma, one per class in typography.css.
/// A style says how text is SHAPED, never what it means — colour stays with
/// the component and comes from a text/* token.
/// </summary>
public enum TextStyle
{
${enumBody}
}

public static class TextStyleExtensions
{
    private static readonly string[] ClassNames =
    {
${lookup}
    };

    /// <summary>
    /// The class name for a style. Pass <paramref name="prose"/> for text that
    /// wraps: every Figma style specifies line-height 100%, which is right for
    /// the single-line labels they were drawn for and too tight for paragraphs.
    /// </summary>
    public static string ToClassName(this TextStyle style, bool prose = false)
    {
        var name = ClassNames[(int)style];
        return prose ? name + " ds-prose" : name;
    }

    /// <summary>Uppercase, wider tracking. Pair with <see cref="TextStyle.Small12Semibold"/>.</summary>
    public const string Overline = "ds-overline";

    public static int Count => ClassNames.Length;
}
`
);

console.log(`TextStyle.g.cs  ${members.length} text styles  ->  ${rel(OUT)}`);
