-- Creates the catalog's database roles. Run once per cluster as a superuser (or the
-- RDS master user) BEFORE the first migration. Group roles are NOLOGIN; the login
-- users below are for local development. In AWS the login users are created by
-- Terraform with `rds_iam` instead of a password (see infra/terraform/catalog/README.md).
--
-- psql -v ON_ERROR_STOP=1 -v dbname=parrot \
--      -v migrator_pw='...' -v writer_pw='...' -v reader_pw='...' -v relay_pw='...' \
--      -f bootstrap-roles.sql
--
-- psql variables are not expanded inside dollar-quoted blocks, so each conditional
-- CREATE ROLE is generated by a SELECT and executed with \gexec.

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'catalog_writer') THEN CREATE ROLE catalog_writer NOLOGIN; END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'catalog_reader') THEN CREATE ROLE catalog_reader NOLOGIN; END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'catalog_outbox_relay') THEN CREATE ROLE catalog_outbox_relay NOLOGIN; END IF;
END $$;

-- The migrator owns the schema. It must NOT be a superuser: FORCE RLS binds the owner,
-- superusers bypass RLS entirely (ADR-004).
SELECT format('CREATE ROLE catalog_migrator LOGIN PASSWORD %L', :'migrator_pw')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'catalog_migrator') \gexec

SELECT format('CREATE ROLE catalog_writer_app LOGIN PASSWORD %L IN ROLE catalog_writer', :'writer_pw')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'catalog_writer_app') \gexec

SELECT format('CREATE ROLE catalog_reader_app LOGIN PASSWORD %L IN ROLE catalog_reader', :'reader_pw')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'catalog_reader_app') \gexec

SELECT format('CREATE ROLE catalog_relay_app LOGIN PASSWORD %L IN ROLE catalog_outbox_relay', :'relay_pw')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'catalog_relay_app') \gexec

-- The migrator creates the schema in the application database; the apps may connect.
GRANT CREATE ON DATABASE :"dbname" TO catalog_migrator;
GRANT CONNECT ON DATABASE :"dbname" TO catalog_migrator, catalog_writer_app, catalog_reader_app, catalog_relay_app;
